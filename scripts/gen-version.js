// Generates src/version.ts from package.json so the UI knows which build it
// is and can warn when the running backend comes from a different install.
import { readFileSync, writeFileSync } from "node:fs";

const pkg = JSON.parse(readFileSync(new URL("../package.json", import.meta.url)));
writeFileSync(
  new URL("../src/version.ts", import.meta.url),
  `// GENERATED by pnpm prebuild — do not edit.\nexport const PLUGIN_VERSION = ${JSON.stringify(pkg.version)};\n`
);
console.log(`version.ts: ${pkg.version}`);
